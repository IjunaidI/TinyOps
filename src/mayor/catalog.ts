// All correspondence and replies are authored fiction. Effects are public policy
// estimates, shared by every controller; no hidden answer key is sent to Jev.
const effect = (
  treasury = 0,
  metrics: Effects["metrics"] = {},
  districtHappiness = 0,
): Effects => ({ treasury, metrics, districtHappiness });
const option = (
  id: string,
  label: string,
  description: string,
  effects: Effects,
  extra: Partial<Pick<RequestOption, "delayed" | "followUp" | "tags">> = {},
): RequestOption => ({ id, label, description, effects, ...extra });
const later = (
  days: number,
  title: string,
  text: string,
  effects: Effects,
) => ({ days, title, text, effects });
type AuthoredRequest = Omit<RequestTemplate, "expiry"> & { expiry?: Effects };
const request = (value: AuthoredRequest): RequestTemplate => ({
  expiry: effect(0, { trust: -1, happiness: -1 }, -2),
  ...value,
});

